"""Перевод ошибок обработки на человеческий язык.

Вывод ffmpeg написан для того, кто знает, что такое поток, контейнер и
муксер. Человеку, который просто сжимал папку с видео, строка
«Invalid data found when processing input» не говорит ничего — и выглядит
как поломка программы, хотя чаще всего дело в самом файле.

Поэтому рядом с полным выводом даём понятную строку: что случилось и что
делать. Сам вывод при этом остаётся — по нему можно разобраться, если
объяснение не подошло или случай новый. Объяснение и вывод идут разными
полями: склеивать их в одну строку значило бы потом угадывать, где
кончается одно и начинается другое.

Тот же приём уже работает для загрузчиков — см. ``download.explain_failure``.
"""

from __future__ import annotations

#: Пары «по каким словам узнаём» → «что написать человеку».
#:
#: Порядок важен: первым идёт то, что распознаётся однозначно. Общие приметы
#: битого файла — последними, иначе они перехватывали бы случаи, где причина
#: известна точнее.
